// Helper: Match a user's active reels against category
export function filterReelsByCategory(reels: Reel[], categoryId: string): Reel[] {
  if (categoryId === 'all') return reels;

  return reels.filter((reel) => {
    const text = `${reel.title} ${reel.caption || ''} ${reel.categoryTag || ''}`.toLowerCase();
    switch (categoryId) {
      case 'ai-ml':
        return text.includes('ai') || text.includes('llm') || text.includes('agent') || text.includes('rag') || text.includes('model') || text.includes('gpt') || text.includes('vector') || text.includes('transformer') || text.includes('deep learning');
      case 'backend-systems':
        return text.includes('backend') || text.includes('redis') || text.includes('kafka') || text.includes('epoll') || text.includes('concurrency') || text.includes('jvm') || text.includes('distributed') || text.includes('socket') || text.includes('queue');
      case 'system-design':
        return text.includes('system design') || text.includes('architecture') || text.includes('microservice') || text.includes('sharding') || text.includes('hashing') || text.includes('uber') || text.includes('netflix') || text.includes('scale');
      case 'cloud-devops':
        return text.includes('devops') || text.includes('docker') || text.includes('kubernetes') || text.includes('k8s') || text.includes('terraform') || text.includes('cloud') || text.includes('aws') || text.includes('sre') || text.includes('container');
      case 'web-dev':
        return text.includes('react') || text.includes('web') || text.includes('frontend') || text.includes('next') || text.includes('javascript') || text.includes('css') || text.includes('html') || text.includes('typescript') || text.includes('vite');
      case 'dsa-algos':
        return text.includes('dsa') || text.includes('algorithm') || text.includes('leetcode') || text.includes('lru') || text.includes('graph') || text.includes('dp') || text.includes('tree') || text.includes('sorting') || text.includes('binary search');
      case 'cybersecurity':
        return text.includes('security') || text.includes('auth') || text.includes('jwt') || text.includes('token') || text.includes('xss') || text.includes('zero trust') || text.includes('crypto') || text.includes('oauth');
      case 'databases':
        return text.includes('database') || text.includes('sql') || text.includes('postgres') || text.includes('b-tree') || text.includes('index') || text.includes('mvcc') || text.includes('nosql') || text.includes('mongo');
      case 'low-level':
        return text.includes('rust') || text.includes('c++') || text.includes('cpu') || text.includes('cache') || text.includes('kernel') || text.includes('memory') || text.includes('assembly') || text.includes('c ');
      case 'mobile-dev':
        return text.includes('mobile') || text.includes('flutter') || text.includes('react native') || text.includes('ios') || text.includes('android') || text.includes('swift') || text.includes('compose');
      case 'ui-ux':
        return text.includes('ui') || text.includes('ux') || text.includes('design') || text.includes('animation') || text.includes('figma') || text.includes('tailwind');
      case 'career-tech':
        return text.includes('career') || text.includes('senior') || text.includes('interview') || text.includes('salary') || text.includes('staff') || text.includes('culture') || text.includes('rfc');
      default:
        return false;
    }
  });
}

// Get all videos across all categories
export function getAllCuratedVideos(): CuratedCategoryVideo[] {
  const all: CuratedCategoryVideo[] = [];
  for (const catId of Object.keys(CURATED_CATEGORY_VIDEOS)) {
    all.push(...CURATED_CATEGORY_VIDEOS[catId]);
  }
  return all;
}
